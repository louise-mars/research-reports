def add_heading(doc, text, level=1, center=False):
    p = doc.add_paragraph()
    p.style = 'Normal'
    run = p.add_run(text)
    run.bold = True
    run.font.size = Pt(16 if level==1 else 14 if level==2 else 12 if level==3 else 11)
    if center:
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    return p

def add_body(doc, text, bold_prefix=None):
    p = doc.add_paragraph()
    p.style = 'Normal'
    p.paragraph_format.line_spacing = Pt(22)
    if bold_prefix:
        r = p.add_run(bold_prefix)
        r.bold = True
        r.font.size = Pt(11)
    r = p.add_run(text)
    r.font.size = Pt(11)
    return p

def add_bullet(doc, text, bold_prefix=None, level=0):
    p = doc.add_paragraph(style='List Bullet')
    p.paragraph_format.left_indent = Inches(0.3 + level * 0.3)
    p.paragraph_format.line_spacing = Pt(20)
    if bold_prefix:
        r = p.add_run(bold_prefix)
        r.bold = True
        r.font.size = Pt(11)
    r = p.add_run(text)
    r.font.size = Pt(11)
    return p

